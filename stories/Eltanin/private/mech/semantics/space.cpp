    auto turn(Semiaxis axis) -> const std::vector<key>& {
        // Order matches Semiaxis enumerators.
        static const std::vector<key>* const byAxis[] = {&turnXp, &turnXn, &turnYp, &turnYn, &turnZp, &turnZn};
        return *byAxis[static_cast<std::size_t>(axis)];
    }

    auto cell2local(key orientation, cell::index lattice) -> vec3 {
        return mat3(matrix[static_cast<std::size_t>(orientation)]) * cell::cell2local(lattice);
    }

    auto cornerIndex(key orientation, cube::Corner corner) -> cube::Corner {
        const ivec3 signedIn = cube::corners[static_cast<std::size_t>(corner)] * 2 - 1;
        const ivec3 want = (matrix[static_cast<std::size_t>(orientation)] * signedIn + 1) / 2;
        for (std::size_t i = 0; i < cube::corners.size(); ++i) {
            if (cube::corners[i] == want) return static_cast<cube::Corner>(i);
        }
        return corner;
    }

